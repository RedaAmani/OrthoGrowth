pub fn table() -> &'static Vec<Row> {
    static T: OnceLock<Vec<Row>> = OnceLock::new();
    T.get_or_init(|| {
        let mut t: Vec<Row> = (0..205).map(|i| Row { age: i as f64 / 12.0, boys: None, girls: None }).collect();
        for (bi, b) in BLOCKS.iter().enumerate() {
            for (j, p) in b.split(';').enumerate() {
                let mut it = p.split(',');
                let parse = |x: Option<&str>| match x { Some("") | None => None, Some(s) => s.parse::<f64>().ok() };
                let boys = parse(it.next());
                let girls = parse(it.next());
                let idx = STARTS[bi] + j;
                t[idx] = Row { age: idx as f64 / 12.0, boys, girls };
            }
        }
        // La source imprime 3,03 pour les filles à 3,08 ans : incohérent ; 2,03 = correction déduite (à vérifier).
        t[37].girls = Some(2.03);
        t
    })
}
